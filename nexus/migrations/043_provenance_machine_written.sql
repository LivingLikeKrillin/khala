-- 043 — 기계가 **쓴** 근거의 등급
--
-- ⛔ **왜 필요한가 (2026-09-23).** 설명 층(picasso-narrator)이 사건마다 낸 LLM 설명을 제
-- 테넌트로 코퍼스에 되돌린다. 「LLM 산출이 LLM 근거가 되는」 순환은 테넌트와 신원으로 막았다
-- — 사건 바퀴는 그 테넌트에 **닿을 수 없는 천장** 아래 돈다.
--
-- 그런데 닿아도 되는 질의(운영자 질의)에서는 그 근거가 **사람이 쓴 문서와 같은 얼굴로**
-- 들어온다. 등급이 없으면 답을 쓰는 모델이 둘을 같은 것으로 다루고, 인용은 그 구별을
-- 약속하지 못한다 (ADR-0010 hop 3 과 같은 논증).
--
-- ⭐ **`machine_read` 와 같은 축의 반대편이다.** 하나는 기계가 그림에서 **읽어** 왔고, 하나는
-- 기계가 **썼다.** 둘 다 사람 문장이 아니고, 요구하는 조심이 다르다 — 읽은 것은 오독을
-- 의심하고, 쓴 것은 **인과를 의심한다.**
--
-- ⚠ **이름에 생산자를 안 넣었다.** 이것은 어휘이지 어느 층의 것이 아니다. 다른 기계가 쓴
-- 코퍼스가 들어와도 같은 말이어야 한다.
--
-- ⚠ `mixed` 는 여기 없다 — 저장되는 값이 아니라 한 제목 아래 등급이 갈릴 때 **표면이 계산해
-- 쓰는 말**이다. 그 비대칭은 이 마이그레이션 이전부터 그랬다.
--
-- ⛔ **`IF NOT EXISTS` 가 필요하다.** 러너가 각 마이그레이션을 트랜잭션으로 감싸고, enum 값
-- 추가는 되돌릴 수 없다 — 두 번 돌면 이것 없이는 실패한다. PG 12+ 에서 트랜잭션 안 추가가
-- 되고(이 배포는 16.13), **같은 트랜잭션 안에서 그 값을 쓰지만 않으면** 된다. 여기서는 안 쓴다.

ALTER TYPE provenance_tier ADD VALUE IF NOT EXISTS 'machine_written';
