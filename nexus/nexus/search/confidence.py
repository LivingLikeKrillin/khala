"""근거가 **얼마나 잘 맞았는가** — 융합이 지워 버린 신호를 되살린다.

RRF 점수는 `1/(k+순위)` 의 합이라 **순위만** 반영한다. 그래서 라이브 코퍼스에서 답할 수 있는
질문과 코퍼스 밖 질문의 최종 점수가 0.029~0.032 로 붙어 버렸고, 시스템은 *"잘 찾았다"* 와
*"309개 중 제일 덜 나쁜 걸 골랐다"* 를 구별하지 못했다. 그 결과가 사용자가 본 것이다:
이름을 물었는데 근거 10개를 채워 기술 스택 표를 길게 답했다.

두 다리는 **이미 크기를 계산한다** — 벡터는 코사인 거리로 정렬하고 키워드는 `ts_rank_cd` 로
정렬한다. 그걸 버리고 순위만 반환하던 것이 결함이다. 2026-08-18 실측(라이브 `default`):

    답할 수 있는 질문 8건   거리 0.191~0.455 · BM25 2.0~4.1
    코퍼스 밖 질문   5건   거리 0.507~0.561 · BM25 0.1~1.0

**위험 구간을 재 봤다 (2026-08-18, 라이브 `default`).** *주제는 코퍼스에 있는데 답이 없는*
질문을 6개 지었는데, 답변까지 돌려 보니 **그중 둘은 코퍼스가 답을 갖고 있었다** — 내 부재
확인이 내 어휘에 묶여 있었던 것이다(문서는 `파티 이름`·`킥/밴` 이라 쓰고 나는 `파티룸 이름`·
`강퇴` 로 찾았다). 그래서 실험군을 다시 나눈다. **이 정정 자체가 이 절의 첫 번째 사실이다:
내 정규식이 못 찾은 것은 부재가 아니다.**

    답할 수 있음 10건  거리 0.191~0.455 · BM25 2.0~4.5   발동 0/10
    주제만 있음   4건  거리 0.377~0.470 · BM25 0.8~1.2   발동 0/4
    코퍼스 밖     3건  거리 0.544~0.575 · BM25 0.1~0.6   발동 3/3

**여기서 `and` 규칙이 값을 한다.** 진짜 중간 구간은 **4건 전부** 키워드 점수가 문턱 아래라
코퍼스 밖과 구별되지 않는다 — 키워드만 보면 넷 다 '밖' 으로 찍힌다. 갈라 주는 것은 벡터
다리뿐이고, 그래서 **둘 다 약할 때만** 판정한다.

**답변 쪽도 같이 봤다 (keyless 브리지, 지출 0).** 중간 구간 4건은 **환각 0건**이었다: 부재를
명시하고(어느 문서를 뒤졌는지까지), 있는 인접 사실은 범위를 밝혀 함께 준다. 답변 길이도
실험군을 따라 갈린다 — 답할 수 있음 평균 570자 · 주제만 있음 342자 · 코퍼스 밖 151자.

⚠ **문턱은 여전히 가설이다.** 질문 17개가 전부 내가 지었고, 중간 구간의 최대 거리(0.470)와
문턱(0.48) 사이가 **0.010** 밖에 안 된다(밖 쪽 여유는 0.064). 실사용 질문 하나가 중간 구간에서
발동하면 그때 0.51 근처로 옮긴다 — 그 트리거를 볼 수 있게 요청마다 거리·키워드 점수를
`search_log.top_distance`·`top_bm25` 에 남긴다(migration 032). 옮기기 전에 **재고**, 재기 전에
표본이 지어낸 것인지 실사용인지 밝힌다.

이 층은 **답을 막지 않는다** — 서술 계약만 바꾼다. 막는 판정은 근거 0건일 때뿐이고 그건
예전 그대로다. 문턱이 틀렸을 때의 피해가 '잘못된 침묵' 이 아니라 '짧은 답' 이 되게 묶은 것이다.

⚠ 임계값은 **코퍼스마다 다를 수 있다.** 벡터 거리는 임베딩 모델의 성질이고(KURE-v1 기준),
키워드 점수는 문서 길이 분포를 탄다. 다른 배포로 옮길 때 재라.
"""

from __future__ import annotations

from dataclasses import dataclass

#: 이보다 **멀면** 벡터 다리가 아무것도 못 붙잡은 것으로 본다. 관측된 경계는 0.455 / 0.507 이고
#: 그 사이를 잡았다. 경계에 딱 붙이지 않는 이유는 표본이 13개이기 때문이다.
FAR_DISTANCE = 0.48
#: 이보다 **낮으면** 키워드 다리가 겉핥은 것으로 본다. 관측 경계는 1.0 / 2.0.
WEAK_BM25 = 1.5


@dataclass(frozen=True)
class Confidence:
    """이번 검색이 얼마나 잘 맞았는가. **랭킹 입력이 아니다** — 서술 계약에만 쓴다."""

    top_distance: float | None = None
    top_bm25: float | None = None

    @property
    def weak(self) -> bool:
        """**두 다리가 모두** 약할 때만 약하다고 말한다.

        한쪽만 약한 것은 흔하다 — 어휘가 안 겹치는 정답(벡터만 잡음), 고유명사 질의(키워드만
        잡음). 하나로 판정하면 정상 답변의 절반이 '코퍼스 밖' 으로 찍힌다.

        다리가 죽어서 값이 없는 경우(`None`)는 **약함의 근거로 쓰지 않는다.** 못 잰 것과
        재서 낮은 것은 다른 사실이고, 이 리포가 반복해서 찾아낸 결함이 그 둘의 혼동이다.
        """
        far = self.top_distance is not None and self.top_distance > FAR_DISTANCE
        weak_kw = self.top_bm25 is not None and self.top_bm25 < WEAK_BM25
        return far and weak_kw

    def describe(self) -> str:
        """사람이 읽을 한 줄. 값이 없으면 빈 문자열(= 프롬프트가 예전과 같다)."""
        if not self.weak:
            return ""
        return (f"근거 적합도 낮음 (벡터 거리 {self.top_distance:.3f} · "
                f"키워드 점수 {self.top_bm25:.2f})")
