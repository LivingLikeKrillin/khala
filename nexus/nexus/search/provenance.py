"""등급 어휘 한 곳 — ADR-0010.

세 표면이 이 값을 사람과 에이전트에게 보여준다(프롬프트·MCP·웹). 각자 문자열을 지어내면
표면마다 다른 말을 하게 되고, 그러면 등급은 표면마다 다른 뜻이 된다.

여기 있는 이유가 하나 더 있다: `nexus/mcp/server.py` 는 설치된 mcp 패키지 버전에 따라 import 가
실패할 수 있고, 그 모듈 안에 표시 함수를 두면 **hop 6 을 테스트할 수 없다.** 이 리포에서
못 도는 테스트는 없는 테스트다.
"""

from __future__ import annotations

AUTHORED = "authored"
MACHINE_READ = "machine_read"
#: 기계가 **쓴** 것. `machine_read` 와 같은 축의 반대편이다 — 하나는 기계가 그림에서 읽어
#: 왔고, 하나는 기계가 지어냈다. 둘 다 사람이 쓴 문장이 아니고, 둘이 요구하는 조심이 다르다.
#:
#: ⛔ **왜 생겼나 (2026-09-23).** 설명 층이 제 설명을 코퍼스로 되돌리면서 「LLM 산출이 LLM
#: 근거가 되는」 순환이 열렸다. 테넌트와 신원으로 **닿는 것**은 막았지만, 닿아도 되는 질의
#: (운영자 질의)에서는 그 근거가 **사람이 쓴 문서와 같은 얼굴로** 들어온다. 이 등급이 그
#: 자리를 가른다.
#:
#: ⚠ **이름에 생산자를 넣지 않았다.** 이것은 어휘이지 어느 층의 것이 아니다 — 다른 기계가
#: 쓴 코퍼스가 들어와도 같은 말이어야 한다.
MACHINE_WRITTEN = "machine_written"
#: 한 제목 아래 두 종류가 섞였다. 하나를 고르면 거짓이 되므로 섞였다고 말한다 — 애매함을
#: 감추는 것은 이 등급이 하는 일의 반대다.
MIXED = "mixed"

#: 프롬프트에 들어가는 문장. 답을 쓰는 모델이 저자가 쓴 문장과 기계가 그림에서 읽은 문장을
#: 구별할 수 있어야, 인용이 그 구별을 약속할 수 있다.
#:
#: **`출처` 라는 낱말을 쓰지 않는다.** 앞선 판은 `출처 종류: …` 였는데, 인용 형식이
#: `[출처: 제목, 섹션]` 이라 모델이 그 라벨을 인용 문자열 안으로 흡수했다 — 2026-08-10 실측에서
#: `[출처: 파티 목록/개설 정책 — Flow 2, 그림에서 기계가 읽은 텍스트]` 가 나왔고, 인용 검증기가
#: 제목을 못 찾아 grounded=False 가 되면서 **멀쩡한 답이 환각으로 분류**됐다. 40건 중 2건.
#: 라벨은 인용 문법과 겹치지 않아야 한다.
PROMPT_NOTE = "⚠ 이 근거는 그림에서 기계가 읽은 것이다 (사람이 쓴 문장이 아니다)"

#: 기계가 **쓴** 근거의 주석. 넷을 말한다 — 무엇인지 · 무엇에 쓰는지 · 무엇에 **안** 쓰는지 ·
#: 사람 근거와 어긋날 때.
#:
#: ⭐ **핵심은 둘째 문장이다** (설명 층이 준 정식화): *이력의 근거로 쓰고 원인의 근거로는
#: 쓰지 마라.* LLM 산출은 **무엇이 언제 있었나**에는 쓸 만하고 **왜**에는 못 쓴다.
#:
#: ⛔ **「다시 확인하라」로 쓰지 않는다.** 첫 초안이 *"원인은 그 설명이 인용한 사람의 문서에서
#: 다시 확인하라"* 였는데, 그 문서가 이번 꾸러미에 **있을 수도 없을 수도** 있다. 못 할 일을
#: 시키면 모델은 무시하거나 **한 척한다.** 지킬 수 있는 모양은 금지다.
#:
#: ⚠ `machine_read` 와 같은 이유로 **`출처` 라는 낱말을 쓰지 않는다** (위 머리말).
MACHINE_WRITTEN_NOTE = (
    "⚠ 이 근거는 LLM 이 만든 지난 설명이다 (사람이 쓴 문장이 아니다). "
    "무엇이 언제 있었나의 근거로만 쓰고, 원인을 이것만으로 단정하지 마라 — "
    "원인을 말하려면 사람이 쓴 근거가 이 꾸러미에 같이 있어야 하고, 없으면 "
    "「지난 설명은 …라고 적었다」까지만 말하라. "
    "사람이 쓴 근거와 어긋나면 사람 쪽을 따르고 어긋났다고 말하라."
)

#: 목록 한 줄에 붙는 짧은 표시.
LIST_MARK = " [그림에서 기계가 읽음]"
MACHINE_WRITTEN_MARK = " [LLM 이 만든 설명]"

#: 등급 → (목록 표시, 프롬프트 주석). **조용한 등급은 여기 없다.**
#:
#: ⛔ 표를 쓰는 이유가 하나다: 등급이 둘이 되는 순간 상수 하나로는 **둘 중 하나가 틀린
#: 문장을 받는다.** 앞선 판은 `mixed` 가 `machine_read` 의 주석을 그대로 썼고, 그때는 섞인
#: 것이 그 둘뿐이라 참이었다.
_SPEAKS: dict[str, tuple[str, str]] = {
    MACHINE_READ: (LIST_MARK, PROMPT_NOTE),
    MACHINE_WRITTEN: (MACHINE_WRITTEN_MARK, MACHINE_WRITTEN_NOTE),
    # ⚠ `mixed` 는 **저장되는 값이 아니다**(DB enum 에 없다). 한 제목 아래 등급이 갈릴 때
    #   표면이 계산해 쓰는 말이고, 지금은 사람 글과 기계가 읽은 것이 섞인 경우다.
    MIXED: (LIST_MARK, PROMPT_NOTE),
}


def mark(tier: str | None) -> str:
    """이 근거에 붙는 목록 표시. 저자 텍스트에는 **아무것도 붙이지 않는다.**

    기본이 조용해야 표시가 뜻을 갖는다 — 전부에 붙이면 아무것도 구별하지 못한다.
    `mixed` 도 표시한다: 섞였다는 것은 확인이 필요하다는 뜻이고, 그게 이 등급이 하는 일이다.
    """
    return _SPEAKS.get(tier or "", ("", ""))[0]


def note_for(tier: str | None) -> str:
    """이 근거에 붙는 프롬프트 주석. 조용한 등급이면 빈 문자열.

    ⛔ **등급마다 다른 문장이다.** 하나를 골라 전부에 붙이면, 기계가 **읽은** 근거에
    *"원인을 단정하지 마라"* 가 붙고 기계가 **쓴** 근거에 *"그림에서 읽었다"* 가 붙는다 —
    둘 다 거짓이고, 거짓인 주석은 없는 주석보다 나쁘다.
    """
    return _SPEAKS.get(tier or "", ("", ""))[1]


def needs_note(tier: str | None) -> bool:
    """이 근거에 프롬프트 주석이 필요한가."""
    return tier in _SPEAKS
